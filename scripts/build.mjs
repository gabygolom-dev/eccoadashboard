import {mkdir,cp,readFile,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
await mkdir('public/assets',{recursive:true});
await cp('src/domain.js','public/assets/domain.js');
await rm('dist',{recursive:true,force:true});
await cp('public','dist',{recursive:true});
const visited=new Set();
async function bundle(file){
 file=path.resolve(file);if(visited.has(file))return '';visited.add(file);
 let source=await readFile(file,'utf8');let deps='';
 for(const match of source.matchAll(/^import\s+.*?from\s+['"](.+?)['"];?\s*$/gm))deps+=await bundle(path.resolve(path.dirname(file),match[1]));
 source=source.replace(/^import\s+.*?from\s+['"].+?['"];?\s*$/gm,'').replace(/\bexport (?=(?:async )?(?:function|const|class)\b)/g,'');
 return deps+`\n// ${path.relative(process.cwd(),file)}\n`+source+'\n';
}
await mkdir('deploy',{recursive:true});
await writeFile('deploy/eccoa-sync-worker.mjs','// Generated by npm run build. Do not add credentials.\n'+await bundle('src/sync-worker.js'));
console.log('Pages: dist/ · Functions: functions/ · Worker para o editor Cloudflare: deploy/eccoa-sync-worker.mjs');
